// Plugin auto-discovery system.
//
// This module scans src/plugins/*/plugin.json at build time and generates
// a registry that the sidebar, search, and routes use to wire up plugins.
//
// To add a new plugin:
//   1. Create src/plugins/<name>/plugin.json
//   2. Create src/plugins/<name>/page.tsx (default export)
//   3. Rebuild — the plugin auto-appears in nav + search + routes
//
// In a real build, this would be a build script that scans the filesystem.
// For the static export, we hardcode the registry here (since plugins are
// bundled at build time anyway).

export interface PluginManifest {
  name: string
  title: string
  description: string
  icon: string          // lucide-react icon name
  category: string
  navOrder: number
  requiredRole: 'demo' | 'admin' | 'enterprise'
  version: string
  author: string
  homepage?: string
  enabled: boolean
}

export interface PluginRegistryEntry extends PluginManifest {
  // The page component to render (lazy-loaded)
  pagePath: string  // e.g. '@/plugins/weather/page'
}

