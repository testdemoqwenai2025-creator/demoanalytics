export function getEnabledPlugins(): PluginRegistryEntry[] {
  return PLUGINS.filter(p => p.enabled).sort((a, b) => a.navOrder - b.navOrder)
}

export function getPluginsForRole(role: 'demo' | 'admin' | 'enterprise' | null): PluginRegistryEntry[] {
  const roleOrder = { demo: 0, admin: 1, enterprise: 2 }
  const userLevel = role ? roleOrder[role] : 0
  return getEnabledPlugins().filter(p => roleOrder[p.requiredRole] <= userLevel)
}

// Icon name → lucide-react component mapping
import {
  Cloud, Plane, Brain, Activity, Newspaper, FolderOpen, Zap, DollarSign, Settings,
  Book, Info, LogIn, Home, LayoutDashboard, TrendingUp, Sparkles,
  type LucideIcon,
} from 'lucide-react'

const ICON_MAP: Record<string, LucideIcon> = {
  cloud: Cloud,
  plane: Plane,
  brain: Brain,
  activity: Activity,
  newspaper: Newspaper,
  folder: FolderOpen,
  zap: Zap,
  dollar: DollarSign,
  settings: Settings,
  book: Book,
  info: Info,
  login: LogIn,
  home: Home,
  dashboard: LayoutDashboard,
  trending: TrendingUp,
  sparkles: Sparkles,
}

export function getPluginIcon(iconName: string): LucideIcon {
  return ICON_MAP[iconName] || Book
}
